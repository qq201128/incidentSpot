def evaluate_daily_trade_floor_rule(feature_row: dict[str, Any]) -> dict[str, Any] | None:
    leaf, conditions = _resolve_leaf(feature_row)
    if not LEAF_ENABLED[leaf]:
        return None
    win_rate = float(LEAF_WIN_RATES[leaf])
    return {
        "name": RULE_NAME,
        "direction": LEAF_DIRECTIONS[leaf],
        "win_rate": win_rate,
        "min_daily_win_rate": win_rate,
        "conditions": conditions,
    }


def _resolve_leaf(feature_row: dict[str, Any]) -> tuple[int, tuple[tuple[str, str, float], ...]]:
    node = ROOT_NODE
    conditions = []
    while TREE_FEATURES[node] != NO_FEATURE:
        feature = FEATURES[TREE_FEATURES[node]]
        threshold = float(TREE_THRESHOLDS[node])
        if _feature_float(feature_row, feature) <= threshold:
            conditions.append((feature, "<=", threshold))
            node = LEFT_CHILDREN[node]
            continue
        conditions.append((feature, ">", threshold))
        node = RIGHT_CHILDREN[node]
    return node, tuple(conditions)


def _feature_float(feature_row: dict[str, Any], feature: str) -> float:
    if feature not in feature_row:
        raise KeyError(f"daily trade floor feature missing: {feature}")
    value = float(feature_row[feature])
    if not math.isfinite(value):
        raise ValueError(f"daily trade floor feature is not finite: {feature}")
    return value
